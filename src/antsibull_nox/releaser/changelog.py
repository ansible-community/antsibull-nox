def lint_fragment_content(
    *,
    fragment_content: dict[str, t.Any],
    config: ChangelogConfig,
) -> list[tuple[int, int, str]]:
    """
    Run linter on the contents of a changelog fragment. Return the list of errors.
    """
    linter = ChangelogFragmentLinter(config)
    fragment = ChangelogFragment(
        content=fragment_content, path="", fragment_format=TextFormat.RESTRUCTURED_TEXT
    )
    errors = linter.lint(fragment)
    return [(line, col, message) for _, line, col, message in errors]


def lint_fragments(
    config: ChangelogConfig,
    fragments: list[ChangelogFragment],
) -> bool:
    """
    Run linter on a given set of changelog fragment objects, and return ``True`` if all pass.
    """
    linter = ChangelogFragmentLinter(config)
    for fragment in fragments:
        if linter.lint(fragment):
            return False
    return True


def setup_config(
    *,
    ansible_doc_bin: str | None,
) -> tuple[PathsConfig, CollectionDetails, ChangelogConfig]:
    """
    Create config objects.
    """
    paths = PathsConfig.force_collection(".", ansible_doc_bin=ansible_doc_bin)
    collection_details = CollectionDetails(paths)
    config = ChangelogConfig.load(paths, collection_details)
    return paths, collection_details, config


def get_changelog_config_and_files(
    *,
    ansible_doc_bin: str | None = None,
    version: Version,
) -> tuple[PathsConfig, ChangelogConfig, list[Path]]:
    """
    Return the paths configuration, the changelog configuration,
    and a list of all changelog files generated by it.

    The changelog file paths are relative to the collection root.
    """
    try:
        paths, _, config = setup_config(ansible_doc_bin=ansible_doc_bin)
    except ChangelogError as exc:
        raise ValueError(
            f"Error while finding release summary in changelog fragments: {exc}"
        ) from exc

    changelogs: list[Path] = []
    version_split = str(version).split(".")
    for output in config.output:
        major_minor_version = ".".join(version_split[: output.filename_version_depth])
        changelog_filename = output.file
        if "%s" in changelog_filename:
            changelog_filename = changelog_filename % (major_minor_version,)
        changelogs.append(Path(changelog_filename))
    return paths, config, changelogs


def find_release_summary(
    fragments: list[ChangelogFragment],
    *,
    config: ChangelogConfig,
) -> tuple[ChangelogFragment, str] | None:
    """
    Check whether there's a release summary in the given list of fragments.
    If yes, return the fragment and the release summary.
    """
    result: tuple[ChangelogFragment, str] | None = None
    for fragment in fragments:
        release_summary = fragment.content.get(config.prelude_name)
        if isinstance(release_summary, str):
            if result is not None:
                raise ValueError(
                    f"Found two release summaries in {fragment.path} and {result[0].path}!"
                )
            result = fragment, release_summary
        elif release_summary is not None:
            raise ValueError(f"Release summary in {fragment.path} is not a string!")
    return result


def check_for_release_summary(
    *,
    ansible_doc_bin: str | None = None,
) -> tuple[ChangelogFragment, str] | None:
    """
    Check whether there's a release summary.
    If yes, return the fragment and the release summary.
    """
    try:
        paths, _, config = setup_config(ansible_doc_bin=ansible_doc_bin)
        fragments = load_fragments(paths, config)
        return find_release_summary(fragments, config=config)
    except ChangelogError as exc:
        raise ValueError(
            f"Error while finding release summary in changelog fragments: {exc}"
        ) from exc


def load_changelog(
    *,
    ansible_doc_bin: str | None = None,
    allow_plugin_cache: bool = False,
) -> tuple[
    PathsConfig,
    CollectionDetails,
    ChangelogConfig,
    ChangesData,
    list[ChangelogFragment],
    list[PluginDescription],
]:
    """
    Load the current changelog data.
    """
    try:
        paths, collection_details, config = setup_config(
            ansible_doc_bin=ansible_doc_bin
        )
        changes = load_changes(config)
        fragments = load_fragments(paths, config)
        plugins = load_plugins(
            paths=paths,
            collection_details=collection_details,
            config=config,
            version=collection_details.version
            or (changes.latest_version if changes.has_release else "dev"),
            force_reload=not allow_plugin_cache,
            ignore_cache=not allow_plugin_cache,
            use_ansible_doc=False,
            add_plugin_period=config.add_plugin_period,
        )
        return paths, collection_details, config, changes, fragments, plugins
    except ChangelogError as exc:
        raise ValueError(f"Error while loading changelog data: {exc}") from exc


def make_release(
    version: Version,
    *,
    cummulative_release: bool = False,
    ansible_doc_bin: str | None = None,
    date: datetime.date | None = None,
) -> None:
    """
    Equivalent of running 'antsibull-changelog release'.
    """
    setup_logger(0)

    if date is None:
        date = datetime.date.today()

    try:
        paths, collection_details, config = setup_config(
            ansible_doc_bin=ansible_doc_bin
        )

        flatmap = _determine_flatmap(collection_details, config)

        codename = None

        changes = load_changes(config)
        if str(version) in changes.releases:
            raise ValueError(f"{version} has already been released!")

        prev_version: str | None = None
        if cummulative_release:
            prev_version = (
                changes.latest_version if changes.has_release else changes.ancestor
            )

        plugins = load_plugins(
            paths=paths,
            collection_details=collection_details,
            config=config,
            version=str(version),
            force_reload=True,
            use_ansible_doc=False,
            add_plugin_period=config.add_plugin_period,
        )
        fragments = load_fragments(paths, config)
        if not lint_fragments(config, fragments):
            raise ValueError(
                "Please fix all linting errors before releasing a new version! "
                "Use `antsibull-changelog lint` to manually lint before releasing."
            )

        if find_release_summary(fragments, config=config) is None:
            raise ValueError(
                f"There is no release_summary for {version} in the changelog fragments."
            )

        args = argparse.Namespace(
            refresh_plugins=None,
            refresh_fragments=None,
            refresh=False,
            reload_plugins=True,
            use_ansible_doc=False,
        )
        plugins, fragments = _do_refresh(
            args, paths, collection_details, config, changes, plugins, fragments
        )
        add_release(
            config,
            changes,
            plugins,
            fragments,
            str(version),
            codename,
            date,
            update_existing=True,
            prev_version=prev_version,
            objects=plugins,
        )
        for output in config.output:
            generate_changelog(
                paths,
                config,
                changes,
                output,
                flatmap=flatmap,
            )
    except ChangelogError as exc:
        raise ValueError(f"Error while adding release to changelog: {exc}") from exc


def render_changelog_extract(
    *,
    fragments: list[ChangelogFragment],
    plugins: list[PluginDescription],
    config: ChangelogConfig,
    collection_details: CollectionDetails,
    text_format: TextFormat,
) -> str:
    """
    ...
    """
    setup_logger(0)

    try:
        changes = ChangesData(config, "")
        fake_version_str = "1.0.0"
        changes.add_release(
            fake_version_str, None, datetime.date.today(), update_existing=False
        )
        for plugin in plugins:
            if plugin.category == "plugin":
                changes.add_plugin(plugin, fake_version_str)
            if plugin.category == "object":
                changes.add_object(plugin, fake_version_str)
        for fragment in fragments:
            changes.add_fragment(fragment, fake_version_str)

        flatmap = _determine_flatmap(collection_details, config)

        generator = ChangelogGenerator(
            config,
            changes,
            flatmap=flatmap,
            render_config=ChangelogOutput(file="", format=text_format),
        )
        renderer = create_document_renderer(text_format, start_level=1)
        generator.generate(renderer, only_latest=True)

        return renderer.render()
    except ChangelogError as exc:
        raise ValueError(f"Error while obtaining changelog excerpt: {exc}") from exc


def get_markdown_extract(
    *,
    version: Version,
    ansible_doc_bin: str | None = None,
    text_format: TextFormat,
) -> str:
    """
    Generate changelog extract for a specific release.
    """
    setup_logger(0)

    try:
        paths = PathsConfig.force_collection(".", ansible_doc_bin=ansible_doc_bin)
        collection_details = CollectionDetails(paths)
        config = ChangelogConfig.load(paths, collection_details)

        flatmap = _determine_flatmap(collection_details, config)

        changes = load_changes(config)
        changes.restrict_to(str(version))

        generator = ChangelogGenerator(
            config,
            changes,
            flatmap=flatmap,
            render_config=ChangelogOutput(file="", format=text_format),
        )
        renderer = create_document_renderer(text_format, start_level=1)
        generator.generate(renderer, only_latest=True)

        return renderer.render()
    except ChangelogError as exc:
        raise ValueError(f"Error while obtaining changelog excerpt: {exc}") from exc


